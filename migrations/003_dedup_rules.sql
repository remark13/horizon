-- SAIA 003 — уточнение правил дедупликации.
--
-- Две правки, обе вызваны разбором первых реальных склеек.
--
-- 1. Правило называлось arxiv_id_in_openalex, но срабатывало 42 раза при
--    39 записях arXiv: на деле оно означает совпадение по arXiv ID, откуда
--    бы запись ни пришла. Причина склейки видна пользователю в карточке
--    сигнала и должна называть то, что действительно произошло.
--
-- 2. Появилось правило blocked_different_doi — не склейка, а отказ от неё.
--    Журнал дедупликации должен фиксировать и решение НЕ объединять: без
--    этого непонятно, почему две одинаково названные записи остались
--    разными работами.

-- Порядок здесь существенный. Менять ограничение, пока в таблице лежат
-- строки со старым значением, нельзя: Postgres проверяет новое ограничение
-- по всем существующим строкам. Но и переименовать значение под старым
-- ограничением тоже нельзя — новое значение в нём не разрешено. Поэтому
-- сначала снимаем ограничение, затем приводим данные, и только потом
-- ставим новое.
ALTER TABLE dedup_decision DROP CONSTRAINT dedup_decision_rule_check;

UPDATE dedup_decision SET rule = 'arxiv_id_match' WHERE rule = 'arxiv_id_in_openalex';

ALTER TABLE dedup_decision ADD CONSTRAINT dedup_decision_rule_check
    CHECK (rule IN (
        'doi_match',
        'arxiv_id_match',
        'title_author_match',
        'blocked_different_doi',
        'new_work'
    ));

INSERT INTO schema_migrations (version) VALUES ('003_dedup_rules');
