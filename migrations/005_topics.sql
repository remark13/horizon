-- SAIA 005 — тематическая разметка OpenAlex на канонической работе.
--
-- Разметка лежала в сырых записях у 100% работ и не использовалась. Она
-- отделяет медицинские и маркетинговые статьи, попавшие в выборку по
-- случайным совпадениям, от работ по теме.
--
-- ГРАНИЦА ИСПОЛЬЗОВАНИЯ, важная настолько, что вынесена в схему:
--
--   МОЖНО фильтровать по field/subfield. Предметная область работы не
--   меняется со временем: статья по гематологии 2014 года была статьёй по
--   гематологии и в 2014-м.
--
--   НЕЛЬЗЯ использовать сам topic как обнаружение сигнала. Тема
--   «Advanced Graph Neural Networks» существует в таксономии OpenAlex
--   потому, что графовые сети СТАЛИ важными. На срезе 2016 года её там не
--   было. Опереться на неё при ретроспективном прогоне значит получить
--   ответ из будущего — та же ловушка, о которой реестр датасетов
--   предупреждает применительно к кластеризации CWTS.

ALTER TABLE work ADD COLUMN primary_topic       TEXT;
ALTER TABLE work ADD COLUMN primary_topic_id    TEXT;
ALTER TABLE work ADD COLUMN primary_field       TEXT;
ALTER TABLE work ADD COLUMN primary_subfield    TEXT;

-- Версия таксономии на момент загрузки: справочник OpenAlex меняется, и
-- без этой отметки нельзя понять, той же ли разметкой посчитаны два прогона.
ALTER TABLE work ADD COLUMN topic_snapshot_date DATE;

CREATE INDEX work_field_idx ON work (mission_id, primary_field);

COMMENT ON COLUMN work.primary_field IS
    'Предметная область. Пригодна для фильтрации на любую дату среза: область работы не меняется со временем.';

COMMENT ON COLUMN work.primary_topic IS
    'Тема из таксономии OpenAlex. НЕ ИСПОЛЬЗОВАТЬ для обнаружения сигнала на ретроспективном срезе: тема могла появиться в справочнике позже даты среза.';

